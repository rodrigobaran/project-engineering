"""N11: nenhum agente aparece como autor, committer ou coautor de commit.

O check compara e-mails, não nomes: o nome é texto livre e muda de máquina para máquina. Ele não
autentica ninguém (qualquer um escreve qualquer identidade no git); o que ele pega é a atribuição
automática que as ferramentas de agente colocam nos commits.

Regras, por commit do intervalo:
- O e-mail do autor está na lista de pessoas.
- O e-mail do committer está na lista, ou é o do GitHub (`noreply@github.com`), que assina o merge e a
  edição feitos pela interface web. O GitHub nunca vale como autor.
- Toda linha de trailer `Algo-by: Nome <email>` (Co-authored-by, Signed-off-by...) traz um e-mail da lista.
- A mensagem não tem marcas de sessão de agente, como `Claude-Session:`.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from . import git

GITHUB_WEB = "noreply@github.com"
_TRAILER = re.compile(r"^\s*([A-Za-z][A-Za-z-]*-by)\s*:\s*(.*)$", re.IGNORECASE | re.MULTILINE)
_EMAIL = re.compile(r"<([^<>\s]+@[^<>\s]+)>")
MARCAS = ("claude-session:", "generated with [claude code]", "generated with claude code", "generated by claude code")
_SEP_CAMPO = "\x1f"
_SEP_COMMIT = "\x1e"


@dataclass(frozen=True)
class Commit:
    sha: str
    autor: str
    email_autor: str
    committer: str
    email_committer: str
    mensagem: str


@dataclass(frozen=True)
class Violacao:
    sha: str
    motivo: str


def ler_commits(raiz: Path, intervalo: str) -> list[Commit]:
    formato = _SEP_CAMPO.join(("%H", "%an", "%ae", "%cn", "%ce", "%B")) + _SEP_COMMIT
    saida = git.rodar(raiz, "log", f"--format={formato}", *git.revisoes(intervalo), "--")
    commits = []
    for bloco in saida.split(_SEP_COMMIT):
        bloco = bloco.lstrip("\n")
        if not bloco:
            continue
        campos = bloco.split(_SEP_CAMPO)
        if len(campos) != 6:
            raise git.ErroGit("saída do git log inesperada")
        commits.append(Commit(*campos))
    return commits


def conferir(commits: list[Commit], pessoas: list[str]) -> list[Violacao]:
    lista = {p.strip().casefold() for p in pessoas if p.strip()}
    if not lista:
        raise ValueError("a lista de pessoas está vazia")
    violacoes = []
    for c in commits:
        curto = c.sha[:7]
        if c.email_autor.casefold() not in lista:
            violacoes.append(Violacao(curto, f"autor fora da lista: {c.autor} <{c.email_autor}>"))
        committer = c.email_committer.casefold()
        if committer not in lista and committer != GITHUB_WEB:
            violacoes.append(Violacao(curto, f"committer fora da lista: {c.committer} <{c.email_committer}>"))
        for chave, valor in _TRAILER.findall(c.mensagem):
            email = _EMAIL.search(valor)
            if email is None or email.group(1).casefold() not in lista:
                violacoes.append(Violacao(curto, f"trailer {chave} fora da lista: {valor.strip()}"))
        mensagem = c.mensagem.casefold()
        for marca in MARCAS:
            if marca in mensagem:
                violacoes.append(Violacao(curto, f"marca de agente na mensagem: {marca!r}"))
    return violacoes
